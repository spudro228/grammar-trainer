/** Фуригана. */
const r = (kanji: string, kana: string) => `<ruby>${kanji}<rt>${kana}</rt></ruby>`

/** Пункт с пропусками. Ответ: строка = один вариант, массив = варианты (обычно кандзи и кана). */
const f = (n: number, text: string, ...answers: (string | string[])[]): Item => ({
  n,
  text,
  answers: answers.map((a) => (Array.isArray(a) ? a : [a])),
})
/** Свободный ответ: один пропуск без проверки. */
const free = (n: number, text: string, blanks = 1): Item => ({ n, text, answers: Array.from({ length: blanks }, () => []) })

