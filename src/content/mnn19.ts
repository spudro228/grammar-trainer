/** Фуригана. */
const r = (kanji: string, kana: string) => `<ruby>${kanji}<rt>${kana}</rt></ruby>`

/** Пункт с пропусками. Ответ: строка = один вариант, массив = варианты (обычно кандзи и кана). */
const f = (n: number, text: string, ...answers: (string | string[])[]): Item => ({
  n,
  text,
  answers: answers.map((a) => (Array.isArray(a) ? a : [a])),
})
/** Свободный ответ: один пропуск без проверки. */
const free = (n: number, text: string, blanks = 1): Item => ({ n, text, answers: Array.from({ length: blanks }, () => []) })
/** Выбор из вариантов. Пропуск в тексте — место выбора. */
const c = (n: number, text: string, options: string[], answer: string): Item => ({ n, text, options, answers: [[answer]] })

let seq = 0
function exercise(label: string, title: string, charts: string, page: number, parts: Part[]): ExerciseBlock {
  seq += 1
  return {
    kind: 'exercise',
    id: `mnn19.${String(seq).padStart(2, '0')}`,
    number: seq,
    label,
    title,
    charts,
    page,
    parts,
  }
}
const one = (type: Part['type'], instruction: string, items: Item[], extra: Partial<Part> = {}): Part[] => [
  { type, instruction, items, ja: true, ...extra },
]
const info = (instruction: string, extra: Partial<Part> = {}): Part[] => [{ type: 'info', instruction, items: [], ja: true, ...extra }]

